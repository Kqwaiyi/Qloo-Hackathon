// The Country list: only the countries and territories Gemini serves, from Google's
// "Available regions" page (https://ai.google.dev/gemini-api/docs/available-regions, updated
// 2026-04-28, 230 entries). It leaves out mainland China, Hong Kong, Macao, Russia, Iran, Cuba,
// Belarus, North Korea and Syria, among others.
//
// Each entry carries its ISO 3166-1 alpha-2 code (as in the `x-vercel-ip-country` header; Kosovo
// uses XK), its display name, the `signal.location.query` sent to Qloo, and Qloo's `key_market`
// tag for it where Qloo has one. Those tags were found on 2026-10-17 through read-only Qloo tag
// lookups, each Country under its own name and its common other names; where Qloo has several,
// the most popular one is kept (`united_states` over `usa`).

export interface Country {
  code: string;
  name: string;
  qlooLocation: string;
  /** The tag on Brands that sell there, such as `urn:tag:key_market:qloo:united_kingdom`, or null when Qloo has none. */
  qlooKeyMarket: `urn:tag:key_market:qloo:${string}` | null;
}

function country(code: string, name: string, { qlooLocation = name, keyMarket }: { qlooLocation?: string; keyMarket?: string } = {}): Country {
  return { code, name, qlooLocation, qlooKeyMarket: keyMarket ? `urn:tag:key_market:qloo:${keyMarket}` : null };
}

